const ERROR_PATTERNS_BN: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^أقصى عدد أكواب للطلب الواحد (\d+)$/, (m) => `এক অর্ডারে সর্বোচ্চ ${m[1]} কাপ।`],
  [/^يجب الانتظار (\d+) ثانية قبل عملية جديدة لنفس العميل$/, (m) => `একই গ্রাহকের জন্য নতুন কাজের আগে ${m[1]} সেকেন্ড অপেক্ষা করুন।`],
];

/** يترجم رسالة خطأ الخادم إلى لغة الكاشير، وإن لم تكن معروفة تبقى كما هي */
export function errorText(message: string, lang: Lang): string {
  if (lang !== "bn") return message;
  const exact = ERRORS_BN[message];
  if (exact) return exact;
  for (const [re, fn] of ERROR_PATTERNS_BN) {
    const m = message.match(re);
    if (m) return fn(m);
  }
  return message;
}
